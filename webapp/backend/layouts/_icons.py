SVG_OPEN = ('<svg class="{cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">')


def resolve_name(name: str | None) -> str | None:
    """日本語キーを実在するアイコン名に解決する。未知なら None。"""
    key = (name or "").strip()
    if not key:
        return None
    if key in _PATHS:
        return key
    return _ALIASES.get(key)


def icon_svg(name: str | None, cls: str = "layout-icon") -> str:
    """<svg> 要素をそのまま返す。未知のキーは空文字（＝無印に落ちる）。

    アイコンが見つからないことを失敗にしない。LLM が思いつきの語を書いても、
    そのシーンだけアイコンが消えるだけで動画生成は止まらない。
    """
    resolved = resolve_name(name)
    if not resolved:
        return ""
    return SVG_OPEN.format(cls=cls) + _PATHS[resolved] + "</svg>"


def icon_names() -> list[str]:
    """編集画面のアイコン選択と、LLM プロンプトに載せる語彙一覧。"""
    return list(_PATHS)
