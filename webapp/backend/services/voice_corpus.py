def _pick(items: list, count: int) -> list:
    """先頭から順に採用し、要求数がコーパスを超える場合はシャッフルして補充する。

    先頭優先にすることで、少ない収録数でも音のバランスが良い文が確実に含まれる。
    """
    if count <= len(items):
        return list(items[:count])
    # コーパスより多く要求された場合は、残りをランダムに繰り返して埋める
    result = list(items)
    extras = random.sample(items, k=min(count - len(items), len(items)))
    result.extend(extras)
    while len(result) < count:
        result.append(random.choice(items))
    return result[:count]


def build_session_items(mode: str, count: int) -> list[dict]:
    """収録モードに応じて、画面に提示する項目のリストを作る。

    返す各項目:
      index       … 1 始まりの通し番号
      prompt      … 画面に大きく表示する文字列（読み上げ文 または 質問）
      instruction … 補助的な指示（トーン指定・回答のしかたなど）
      kind        … "read"（読み上げる）/ "answer"（声で答える）
    """
    if mode not in SUPPORTED_MODES:
        raise ValueError(f"未対応の収録モードです: {mode}")

    items: list[dict] = []
    if mode == MODE_SCRIPT:
        for i, text in enumerate(_pick(SCRIPT_SENTENCES, count), start=1):
            items.append({
                "index": i,
                "prompt": text,
                "instruction": "表示された文をそのまま読み上げてください。",
                "kind": "read",
            })
    elif mode == MODE_CHAT:
        for i, question in enumerate(_pick(CHAT_QUESTIONS, count), start=1):
            items.append({
                "index": i,
                "prompt": question,
                "instruction": "質問に対して、20秒程度を目安に声で自由にお答えください。",
                "kind": "answer",
            })
    else:  # MODE_EMOTION
        for i, (text, tone) in enumerate(_pick(EMOTION_ITEMS, count), start=1):
            items.append({
                "index": i,
                "prompt": text,
                "instruction": f"{tone} 読み上げてください。",
                "kind": "read",
            })
    return items
